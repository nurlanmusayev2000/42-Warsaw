#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	unsigned int	i;
	unsigned int	length;
	char			*res;

	i = 0;
	if (!s)
		return (NULL);
	length = ft_strlen(s);
	res = (char *)malloc(length * sizeof(char) + 1);
	if (!res)
	{
		return (NULL);
	}
	while (i < length)
	{
		res[i] = (*f)(i, s[i]);
		i++;
	}
	res[i] = '\0';
	return (res);
}
